use std::{
    collections::BTreeMap,
    fmt::Write as _,
    path::{Path, PathBuf},
};

use crate::{
    Error,
    ports::{Endpoints, LanePorts, PortBlock, PortRequest, lane_endpoints},
};

/// Label keys devlanes puts on per-lane compose containers. Compose's own
/// `com.docker.compose.*` labels stay untouched.
pub mod labels {
    pub const PROJECT: &str = "dev.devlanes.project";
    pub const LANE: &str = "dev.devlanes.lane";
    pub const SERVICE: &str = "dev.devlanes.service";
    pub const KIND: &str = "dev.devlanes.kind";
    pub const SCOPE: &str = "dev.devlanes.scope";
}

/// File name of the generated override. It must not match Compose's automatic
/// `compose.override.yaml` lookup, so running Compose by hand in the state directory never
/// picks it up implicitly.
pub const OVERRIDE_FILE: &str = "devlanes.compose-override.yaml";

/// A rendered per-lane override and the endpoints its ports produce.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LaneOverride {
    pub yaml: String,
    pub endpoints: Endpoints,
}

/// Labels for one per-lane compose service.
pub fn lane_labels(project: &str, lane: u32, service: &str) -> BTreeMap<String, String> {
    BTreeMap::from([
        (labels::PROJECT.to_owned(), project.to_owned()),
        (labels::LANE.to_owned(), lane.to_string()),
        (labels::SERVICE.to_owned(), service.to_owned()),
        (labels::KIND.to_owned(), "compose".to_owned()),
        (labels::SCOPE.to_owned(), "lane".to_owned()),
    ])
}

/// Renders the override for `services` of lane `lane`. Ports use `!override` because a
/// plain merge would append and keep the base file's fixed host ports; `container_name`
/// uses `!reset` because a fixed name collides on the second lane. Host ports bind to
/// 127.0.0.1 so lane databases are not exposed on the LAN.
///
/// `requests` comes from [`crate::port_requests`] and every request needs a host port in
/// `ports` inside `block`.
pub fn render_override(
    project: &str,
    lane: u32,
    services: &[String],
    requests: &[PortRequest],
    ports: &LanePorts,
    block: PortBlock,
) -> Result<LaneOverride, Error> {
    let endpoints = lane_endpoints(requests, ports, block)?;
    let mut yaml = format!(
        "# Generated by devlanes for lane {lane} of {project}; rewritten on every start.\nservices:\n"
    );
    for service in services {
        // `writeln!` into a String cannot fail; the results are ignored for that reason.
        let _ = writeln!(yaml, "  {}:", quote(service));
        yaml.push_str("    container_name: !reset null\n");
        let mappings: Vec<String> = requests
            .iter()
            .filter(|request| &request.service == service)
            .filter_map(|request| {
                let host = endpoints.get(service)?.ports.get(&request.target)?;
                Some(format!(
                    "127.0.0.1:{host}:{}/{}",
                    request.target, request.protocol
                ))
            })
            .collect();
        if mappings.is_empty() {
            yaml.push_str("    ports: !reset []\n");
        } else {
            yaml.push_str("    ports: !override\n");
            for mapping in mappings {
                let _ = writeln!(yaml, "      - {}", quote(&mapping));
            }
        }
        yaml.push_str("    labels:\n");
        for (key, value) in lane_labels(project, lane, service) {
            let _ = writeln!(yaml, "      {}: {}", quote(&key), quote(&value));
        }
    }
    Ok(LaneOverride { yaml, endpoints })
}

/// Writes the override into `dir` through a temporary file and rename, so a concurrent
/// `docker compose` never reads a half-written file. Returns the file path.
pub async fn write_override(dir: &Path, yaml: &str) -> Result<PathBuf, Error> {
    tokio::fs::create_dir_all(dir).await?;
    let path = dir.join(OVERRIDE_FILE);
    let temporary = dir.join(format!(".{OVERRIDE_FILE}.tmp"));
    tokio::fs::write(&temporary, yaml).await?;
    tokio::fs::rename(&temporary, &path).await?;
    Ok(path)
}

/// JSON strings are valid YAML double-quoted scalars, which avoids YAML's implicit typing
/// (`"on"`, `"0123"`) and escaping rules for names and label values.
fn quote(text: &str) -> String {
    serde_json::Value::String(text.to_owned()).to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn request(service: &str, target: u16, protocol: &str) -> PortRequest {
        PortRequest {
            service: service.into(),
            target,
            protocol: protocol.into(),
        }
    }

    #[test]
    fn renders_override_with_tags_and_labels() {
        let block = PortBlock::new(21000, 10).expect("valid block");
        let services = ["mailpit".to_owned(), "worker".to_owned()];
        let requests = [
            request("mailpit", 8025, "tcp"),
            request("mailpit", 1025, "tcp"),
        ];
        let ports = LanePorts::from([(
            "mailpit".to_owned(),
            BTreeMap::from([(8025, 21000), (1025, 21001)]),
        )]);
        let rendered =
            render_override("acme", 2, &services, &requests, &ports, block).expect("valid");
        let expected = r#"# Generated by devlanes for lane 2 of acme; rewritten on every start.
services:
  "mailpit":
    container_name: !reset null
    ports: !override
      - "127.0.0.1:21000:8025/tcp"
      - "127.0.0.1:21001:1025/tcp"
    labels:
      "dev.devlanes.kind": "compose"
      "dev.devlanes.lane": "2"
      "dev.devlanes.project": "acme"
      "dev.devlanes.scope": "lane"
      "dev.devlanes.service": "mailpit"
  "worker":
    container_name: !reset null
    ports: !reset []
    labels:
      "dev.devlanes.kind": "compose"
      "dev.devlanes.lane": "2"
      "dev.devlanes.project": "acme"
      "dev.devlanes.scope": "lane"
      "dev.devlanes.service": "worker"
"#;
        assert_eq!(rendered.yaml, expected);
        assert_eq!(rendered.endpoints["mailpit"].port, Some(21000));
        assert!(!rendered.endpoints.contains_key("worker"));
    }

    #[test]
    fn quotes_awkward_names() {
        assert_eq!(quote("on"), "\"on\"");
        assert_eq!(quote("a\"b"), "\"a\\\"b\"");
        assert_eq!(quote("x: y #z"), "\"x: y #z\"");
    }

    #[test]
    fn rejects_unassigned_ports() {
        let block = PortBlock::new(21000, 10).expect("valid block");
        let requests = [request("mailpit", 8025, "tcp")];
        let result = render_override(
            "acme",
            1,
            &["mailpit".to_owned()],
            &requests,
            &LanePorts::new(),
            block,
        );
        assert!(matches!(result, Err(Error::MissingPortAssignment { .. })));
    }

    #[tokio::test]
    async fn writes_atomically_into_state_dir() {
        let dir = tempfile::tempdir().expect("tempdir");
        let nested = dir.path().join("lanes/acme/2");
        let path = write_override(&nested, "services: {}\n")
            .await
            .expect("write");
        assert_eq!(path, nested.join(OVERRIDE_FILE));
        assert_eq!(
            tokio::fs::read_to_string(&path).await.expect("read"),
            "services: {}\n"
        );
        let leftovers: Vec<_> = std::fs::read_dir(&nested).expect("list").collect();
        assert_eq!(leftovers.len(), 1);
    }
}
