//! Writes the merged draft as `devlanes.yaml` text with notes as comments.
//!
//! A hand-written emitter keeps comments next to the units they concern and the key order
//! of the reference docs, which a serializer would not.

use std::fmt::Write as _;

use crate::{
    Note,
    draft::{Check, Command, Unit},
};

/// Everything that ends up in the file.
pub(crate) struct Document<'a> {
    pub project: &'a str,
    /// Source files, for the header.
    pub files: &'a [String],
    pub global_env: &'a [(String, String)],
    pub services: &'a [(String, Unit)],
    pub tasks: &'a [(String, Unit)],
    /// Notes that belong to no unit.
    pub notes: &'a [Note],
    /// A Compose file to suggest as `infra.compose`.
    pub compose: Option<&'a str>,
}

/// Renders the document.
pub(crate) fn render(doc: &Document<'_>) -> String {
    let mut out = String::new();
    out.push_str("# yaml-language-server: $schema=https://devlanes.run/v1/schema.json\n");
    let _ = writeln!(
        out,
        "# Generated by `devlanes migrate` from {}.",
        doc.files.join(", ")
    );
    out.push_str("# Comments starting with \"migrated from\" are notes to review.\n");
    for note in doc.notes {
        comment(
            &mut out,
            0,
            &format!("migrated from {}: {}", note.source, note.message),
        );
    }
    let _ = writeln!(out, "project: {}", scalar(doc.project));
    if !doc.global_env.is_empty() {
        out.push_str("global_env:\n");
        env_map(&mut out, 1, doc.global_env);
    }
    if !doc.services.is_empty() {
        out.push_str("services:\n");
        for (name, unit) in doc.services {
            write_unit(&mut out, name, unit);
        }
    }
    if !doc.tasks.is_empty() {
        out.push_str("tasks:\n");
        for (name, unit) in doc.tasks {
            write_unit(&mut out, name, unit);
        }
    }
    if let Some(compose) = doc.compose {
        comment(
            &mut out,
            0,
            &format!(
                "migrated from {compose}: to run its containers as shared infra (one set for all lanes), uncomment:"
            ),
        );
        out.push_str("# infra:\n");
        let _ = writeln!(out, "#   compose: {}", scalar(compose));
    }
    out
}

/// Two spaces per level.
fn indent(level: usize) -> String {
    "  ".repeat(level)
}

/// A one-line comment; newlines in the text become spaces.
fn comment(out: &mut String, level: usize, text: &str) {
    let text = text.replace(['\n', '\r'], " ");
    let _ = writeln!(out, "{}# {}", indent(level), text.trim_end());
}

/// One service or task entry.
fn write_unit(out: &mut String, name: &str, unit: &Unit) {
    if let Some(description) = &unit.description {
        comment(out, 1, description);
    }
    for note in &unit.notes {
        comment(out, 1, &format!("migrated from {}: {note}", unit.file));
    }
    let _ = writeln!(out, "  {}:", key(name));
    match &unit.run {
        Command::Shell(text) => field(out, 2, "run", text),
        Command::Argv(args) => list(out, 2, "run", args),
        Command::Script { source, name } => {
            field(out, 2, "run_script", &format!("{source}#{name}"));
        }
        Command::Steps(steps) => list(out, 2, "steps", steps),
    }
    if let Some(cwd) = &unit.cwd {
        field(out, 2, "cwd", cwd);
    }
    if !unit.env.is_empty() {
        out.push_str("    env:\n");
        env_map(out, 3, &unit.env);
    }
    if let Some(autostart) = unit.autostart {
        let _ = writeln!(out, "    autostart: {autostart}");
    }
    if let Some(replicas) = unit.replicas {
        let _ = writeln!(out, "    replicas: {replicas}");
    }
    if !unit.tags.is_empty() {
        list(out, 2, "tags", &unit.tags);
    }
    if let Some(ready) = &unit.ready {
        out.push_str("    ready:\n");
        match &ready.check {
            Check::Tcp => out.push_str("      tcp: true\n"),
            Check::Http { path, status } => {
                out.push_str("      http:\n");
                field(out, 4, "path", path);
                if let Some(status) = status {
                    let _ = writeln!(out, "        status: {status}");
                }
            }
            Check::Log(pattern) => field(out, 3, "log", pattern),
            Check::Cmd(Command::Argv(args)) => list(out, 3, "cmd", args),
            Check::Cmd(Command::Shell(text)) => field(out, 3, "cmd", text),
            // Sources only build readiness commands as shell text or argv.
            Check::Cmd(Command::Script { .. } | Command::Steps(_)) => {}
            // Settled before rendering; see `ports::settle_probe`.
            Check::Probe { .. } => {}
        }
        if let Some(timeout) = &ready.timeout {
            field(out, 3, "timeout", timeout);
        }
    }
    if unit.stop_signal.is_some() || unit.stop_timeout.is_some() {
        out.push_str("    stop:\n");
        if let Some(signal) = &unit.stop_signal {
            field(out, 3, "signal", signal);
        }
        if let Some(timeout) = &unit.stop_timeout {
            field(out, 3, "timeout", timeout);
        }
    }
    if let Some(when) = unit.when {
        let _ = writeln!(out, "    when: {}", when.as_str());
    }
    if unit.after_services {
        out.push_str("    after: services\n");
    }
    if unit.interactive {
        out.push_str("    interactive: true\n");
    }
    if let Some(confirm) = &unit.confirm {
        field(out, 2, "confirm", confirm);
    }
}

/// `key: value`, with a block scalar for multi-line text.
fn field(out: &mut String, level: usize, name: &str, value: &str) {
    let pad = indent(level);
    if value.contains('\n') && block_safe(value) {
        let chomp = if value.ends_with('\n') { "" } else { "-" };
        let _ = writeln!(out, "{pad}{name}: |{chomp}");
        let inner = indent(level + 1);
        for line in value.trim_end_matches('\n').split('\n') {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "{inner}{line}");
            }
        }
    } else {
        let _ = writeln!(out, "{pad}{name}: {}", scalar(value));
    }
}

/// A block list under `name`.
fn list(out: &mut String, level: usize, name: &str, items: &[String]) {
    let pad = indent(level);
    let _ = writeln!(out, "{pad}{name}:");
    for item in items {
        let _ = writeln!(out, "{pad}  - {}", scalar(item));
    }
}

/// `KEY: value` lines.
fn env_map(out: &mut String, level: usize, env: &[(String, String)]) {
    let pad = indent(level);
    for (name, value) in env {
        let _ = writeln!(out, "{pad}{}: {}", key(name), scalar(value));
    }
}

/// A literal block keeps the text exactly when no line starts with a space (that would need
/// an indentation indicator) and no line has trailing spaces or carriage returns.
fn block_safe(text: &str) -> bool {
    let body = text.trim_end_matches('\n');
    !body.starts_with([' ', '\t'])
        && !body.contains('\r')
        && !body.ends_with('\n')
        && body
            .split('\n')
            .all(|line| !line.ends_with([' ', '\t']) && !line.contains('\u{feff}'))
        && !text.ends_with("\n\n")
}

/// A mapping key: plain when it is a simple identifier.
fn key(text: &str) -> String {
    let simple = text
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && text
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'))
        && !reserved(text);
    if simple {
        text.to_owned()
    } else {
        quoted(text)
    }
}

/// A scalar value: plain when YAML reads it back as the same string, else double-quoted.
pub(crate) fn scalar(text: &str) -> String {
    if plain_safe(text) {
        text.to_owned()
    } else {
        quoted(text)
    }
}

/// JSON string syntax is valid YAML double-quoted syntax.
fn quoted(text: &str) -> String {
    serde_json::to_string(text).unwrap_or_else(|_| format!("\"{text}\""))
}

/// Words YAML reads as booleans or null.
fn reserved(text: &str) -> bool {
    matches!(
        text.to_ascii_lowercase().as_str(),
        "true" | "false" | "yes" | "no" | "on" | "off" | "null" | "y" | "n" | "~"
    )
}

/// Whether `text` can be written without quotes.
fn plain_safe(text: &str) -> bool {
    let Some(first) = text.chars().next() else {
        return false;
    };
    if crate::draft::duration_text(text).as_deref() == Some(text) {
        return true;
    }
    let allowed = |c: char| c.is_ascii_alphanumeric() || " -_./:=@%+$(){}'~,".contains(c);
    (first.is_ascii_alphabetic() || matches!(first, '.' | '/' | '_' | '$'))
        && text.chars().all(allowed)
        && !text.ends_with([' ', ':'])
        && !text.contains(": ")
        && !text.contains(" #")
        && !reserved(text)
        && text.parse::<f64>().is_err()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quotes_only_when_needed() {
        assert_eq!(scalar("npm run dev"), "npm run dev");
        assert_eq!(scalar("3000"), "\"3000\"");
        assert_eq!(scalar("true"), "\"true\"");
        assert_eq!(scalar("echo a: b"), "\"echo a: b\"");
        assert_eq!(scalar("--port"), "\"--port\"");
        assert_eq!(scalar("${{ self.port }}"), "${{ self.port }}");
        assert_eq!(scalar("a \"b\""), "\"a \\\"b\\\"\"");
        assert_eq!(scalar("# not a comment"), "\"# not a comment\"");
    }
}
